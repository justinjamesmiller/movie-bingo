export function getSubgenres(genre) {
  return SUBGENRES_BY_GENRE[genre] || SUBGENRES_BY_GENRE[DEFAULT_GENRE];
}

function shuffle(arr) {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

// All trope texts eligible for a given genre + sub-genre (general ∪
// sub-genre-specific), independent of any particular game's pool -- used to
// draw a replacement trope from a specific sub-genre when a swap-out is
// approved (see GameClient proposeReplace / _resolveClaim).
export function getEligibleTropeTexts(genre, subgenre) {
  return TROPES.filter(
    (tr) => tr.genre === genre && (tr.subgenres.includes('general') || tr.subgenres.includes(subgenre)),
  ).map((tr) => tr.text);
}

// Picks `totalTropes` distinct trope texts for a game's shared pool. Supports
// multiple genres and multiple sub-genre picks at once (e.g. a movie that's
// Horror/Comedy/Romance spanning several sub-genres): `genres` is an array of
// genre ids, always contributing their "general" pool; `subgenreSelections`
// is an array of `{genre, subgenre}` pairs for additional specific sub-genres
// layered on top (each `genre` should be one of the selected `genres`).
// `generalPercents` is a `{[genre]: percent}` map -- EACH genre gets its own
// independent general/specific mix slider, applied to that genre's own share
// of the pool (the total is split evenly across genres first, then each
// genre's allocation is filled per its own percent). Falls back to topping up
// from whichever pools have leftovers (that genre's own first, then any
// other selected genre's) if a genre's exact allocation/mix can't be met --
// gracefully degrades to however many unique tropes actually exist overall if
// fewer than `totalTropes` in total.
export function pickTropePool(genres, subgenreSelections, generalPercents, totalTropes) {
  const perGenreBase = Math.floor(totalTropes / genres.length);
  let remainder = totalTropes - perGenreBase * genres.length;

  const chosen = [];
  const used = new Set();
  const leftoverPool = [];

  for (const genre of genres) {
    const allocation = perGenreBase + (remainder > 0 ? 1 : 0);
    if (remainder > 0) remainder--;

    const pct = generalPercents[genre] ?? DEFAULT_GENERAL_PERCENT;
    const generalPool = shuffle(
      TROPES.filter((tr) => tr.genre === genre && tr.subgenres.includes('general')).map((tr) => tr.text),
    );
    const specificPool = shuffle(
      TROPES.filter((tr) => subgenreSelections.some((s) => s.genre === genre && tr.subgenres.includes(s.subgenre))).map(
        (tr) => tr.text,
      ),
    );

    const desiredGeneral = Math.round((allocation * pct) / 100);
    const generalCount = Math.min(desiredGeneral, generalPool.length, allocation);
    const specificCount = Math.min(allocation - generalCount, specificPool.length);

    const genreChosen = [...generalPool.slice(0, generalCount), ...specificPool.slice(0, specificCount)];
    if (genreChosen.length < allocation) {
      const usedLocal = new Set(genreChosen);
      for (const text of [...generalPool, ...specificPool]) {
        if (genreChosen.length >= allocation) break;
        if (usedLocal.has(text)) continue;
        usedLocal.add(text);
        genreChosen.push(text);
      }
    }

    const usedLocalFinal = new Set(genreChosen);
    for (const text of [...generalPool, ...specificPool]) {
      if (!usedLocalFinal.has(text)) leftoverPool.push(text);
    }
    for (const text of genreChosen) {
      if (!used.has(text)) {
        used.add(text);
        chosen.push(text);
      }
    }
  }

  if (chosen.length < totalTropes) {
    for (const text of shuffle(leftoverPool)) {
      if (chosen.length >= totalTropes) break;
      if (used.has(text)) continue;
      used.add(text);
      chosen.push(text);
    }
  }

  return shuffle(chosen).slice(0, totalTropes);
}

// Builds one player's personal board by sampling from the game's shared
// trope pool (see pickTropePool above / GameClient.hostGame).
export function buildPlayerBoard(pool, useFreeSpace = false) {
  const size = useFreeSpace ? 24 : 25;
  const chosen = shuffle(pool).slice(0, size);
  if (!useFreeSpace) return chosen;

  const board = Array.from({ length: 25 });
  let idx = 0;
  for (let i = 0; i < 25; i++) {
    board[i] = i === CENTER_INDEX ? FREE_SPACE_TEXT : chosen[idx++];
  }
  return board;
}
